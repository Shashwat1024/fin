import { mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { _electron as electron, expect, test } from '@playwright/test'

// Visual review aid: SCREENSHOTS=1 npx playwright test screenshots
test.skip(!process.env.SCREENSHOTS, 'Set SCREENSHOTS=1 to capture screenshots')

test('capture main screens', async () => {
  const dataDir = mkdtempSync(join(tmpdir(), 'fin-shots-'))
  const { ELECTRON_RUN_AS_NODE: _ignored, ...env } = process.env
  const app = await electron.launch({ args: ['.'], env: { ...env, FIN_DATA_DIR: dataDir } as Record<string, string> })
  const page = await app.firstWindow()
  await page.setViewportSize({ width: 1320, height: 860 })
  page.on('pageerror', (e) => console.log('PAGEERROR', e.message, e.stack?.split('\n').slice(0, 4).join(' | ')))
  page.on('console', (m) => m.type() === 'error' && console.log('CONSOLE', m.text().slice(0, 400)))
  const out = (name: string) => join('test-results', 'screens', `${name}.png`)
  const toast = (t: string) => page.locator('[data-sonner-toast]', { hasText: t }).last()

  await expect(page.getByText('Welcome to Fin')).toBeVisible()
  await page.screenshot({ path: out('01-onboarding') })
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByLabel('Name').fill('HDFC Savings')
  await page.getByLabel('Balance on start date').fill('1,25,000')
  await page.getByRole('button', { name: 'Add account and finish' }).click()

  const add = async (amount: string, payee: string, category: string, mode = 'Control+n') => {
    await page.keyboard.press(mode)
    await page.getByLabel('Amount').fill(amount)
    await page.getByLabel('Payee').fill(payee)
    await page.getByRole('combobox', { name: 'Category' }).click()
    await page.getByPlaceholder('Search categories…').fill(category)
    await page.keyboard.press('Enter')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(toast('Transaction added')).toBeVisible()
  }
  await add('85000', 'ACME Payroll', 'Salary', 'Control+i')
  await add('450', 'Swiggy', 'Food delivery')
  await add('2,340.50', 'DMart', 'Groceries')
  await add('18,000', 'Rent — Koramangala flat', 'Rent')
  await add('649', 'Netflix', 'Subscriptions')
  await page.keyboard.press('Escape')

  await page.keyboard.press('Control+1')
  await page.waitForTimeout(4500) // let toasts fade
  await page.screenshot({ path: out('02-overview-light') })
  await page.getByRole('button', { name: /^Cash position: data as of/ }).click()
  await page.screenshot({ path: out('10-freshness') })
  await page.keyboard.press('Escape')
  await page.getByRole('radio', { name: 'Table' }).click()
  await page.screenshot({ path: out('11-chart-table'), fullPage: true })
  await page.getByRole('link', { name: /^Spent this month/ }).click()
  await page.screenshot({ path: out('12-drill-spent') })
  await page.keyboard.press('Control+1')
  await page.getByRole('link', { name: /^Cash position/ }).click()
  await page.screenshot({ path: out('13-drill-cash') })
  await page.keyboard.press('Control+2')
  await page.screenshot({ path: out('03-transactions') })
  await page.keyboard.press('Control+n')
  await page.getByRole('button', { name: 'Split' }).click()
  await page.screenshot({ path: out('04-dialog-split') })
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+3')
  await page.screenshot({ path: out('05-accounts') })
  await page.keyboard.press('Control+4')
  await page.getByLabel('Statement file').setInputFiles(join('tests', 'fixtures', 'csv', 'hdfc_savings.csv'))
  await expect(page.getByText('5 transactions')).toBeVisible()
  await page.screenshot({ path: out('08-import-mapping') })
  await page.getByRole('button', { name: 'Check for duplicates' }).click()
  await expect(page.getByText('Balance check')).toBeVisible()
  await page.screenshot({ path: out('09-import-review'), fullPage: true })
  await page.keyboard.press('Control+3')
  await page.keyboard.press('Control+k')
  await page.screenshot({ path: out('06-command-palette') })
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+,')
  await page.getByRole('button', { name: 'Back up now' }).click()
  await page.getByRole('button', { name: 'Back up', exact: true }).click()
  await page.waitForTimeout(300)
  await page.getByRole('button', { name: 'Back up now' }).click()
  await page.getByLabel('Protect with a passphrase').click()
  await page.screenshot({ path: out('14-backup-dialog') })
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /^Restore backup/ }).first().click()
  await expect(page.getByRole('button', { name: 'Replace my data' })).toBeVisible()
  await page.screenshot({ path: out('15-restore-confirm') })
  await page.keyboard.press('Escape')
  await page.getByText('Backups', { exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: out('16-settings-data') })
  await page.getByRole('button', { name: 'Explore demo data' }).click()
  await expect(page.getByText('Demo Savings Bank').first()).toBeVisible()
  await page.waitForTimeout(4500)
  await page.screenshot({ path: out('17-demo-overview') })
  await page.keyboard.press('Control+5')
  await expect(page.getByText('All recurring items')).toBeVisible()
  await page.screenshot({ path: out('18-recurring'), fullPage: true })
  await page.keyboard.press('Control+6')
  await expect(page.getByTestId('to-assign')).toBeVisible()
  await page.getByLabel('Assigned to Groceries').focus()
  await page.screenshot({ path: out('19-budget'), fullPage: true })
  await page.keyboard.press('Control+7')
  await expect(page.getByTestId('goal-status').first()).toBeVisible()
  await page.screenshot({ path: out('20-goals') })
  await page.keyboard.press('Control+1')
  await page.getByText('Due in the next 14 days').scrollIntoViewIfNeeded()
  await page.screenshot({ path: out('21-overview-planning') })
  await page.keyboard.press('Control+9')
  await expect(page.getByRole('region', { name: 'Assumptions' })).toBeVisible()
  await page.locator('svg[role="img"]').hover({ position: { x: 400, y: 120 } })
  await page.waitForTimeout(300)
  await page.screenshot({ path: out('28-forecast'), fullPage: true })
  await page.keyboard.press('Control+0')
  await expect(page.getByRole('region', { name: 'Assets' })).toBeVisible()
  await page.waitForTimeout(300)
  await page.screenshot({ path: out('29-networth'), fullPage: true })
  await page.getByRole('button', { name: 'Update value of Index Fund SIP' }).click()
  await page.waitForTimeout(400)
  await page.screenshot({ path: out('30-valuation-dialog') })
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+2')
  await expect(page.getByText('Food delivery?').first()).toBeVisible()
  await page.screenshot({ path: out('23-suggestions') })
  await page.keyboard.press('Control+8')
  await page.screenshot({ path: out('24-categories') })
  await page.getByRole('tab', { name: 'Rules' }).click()
  await page.screenshot({ path: out('25-rules') })
  await page.getByRole('button', { name: 'New rule' }).first().click()
  await page.getByRole('dialog').getByLabel('Name').fill('Swiggy')
  await page.getByLabel('Condition 1 text').fill('swiggy')
  await page.getByRole('dialog').getByRole('combobox', { name: 'Category' }).click()
  await page.getByPlaceholder('Search categories…').fill('Food delivery')
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('rule-live-count')).toContainText('Matches')
  await page.waitForTimeout(400)
  await page.screenshot({ path: out('26-rule-dialog') })
  await page.getByRole('button', { name: 'Add rule' }).click()
  await expect(page.getByRole('dialog', { name: /Apply/ })).toBeVisible()
  await page.waitForTimeout(400)
  await page.screenshot({ path: out('27-apply-rule') })
  await page.keyboard.press('Escape')
  await page.evaluate("location.hash = '/insights'")
  await expect(page.getByRole('article').first()).toBeVisible()
  await page.waitForTimeout(300)
  await page.screenshot({ path: out('32-insights'), fullPage: true })
  await page.getByRole('tab', { name: 'What if' }).click()
  const form = page.getByRole('form', { name: 'Add a change' })
  await form.getByLabel('Name').fill('New laptop')
  await form.getByLabel('Amount').fill('150000')
  await form.getByRole('button', { name: 'Add to scenario' }).click()
  await form.getByLabel('Change').click()
  await page.getByRole('option', { name: 'Save more each month' }).click()
  await form.getByLabel('Towards').click()
  await page.getByRole('option', { name: 'Emergency fund' }).click()
  await form.getByLabel('Amount a month').fill('10000')
  await form.getByRole('button', { name: 'Add to scenario' }).click()
  await expect(page.getByRole('region', { name: 'How this was worked out' })).toContainText('Emergency fund')
  await page.waitForTimeout(400)
  await page.screenshot({ path: out('33-what-if'), fullPage: true })
  await page.keyboard.press('Control+5')
  await expect(page.getByRole('region', { name: 'Looks recurring' })).toBeVisible()
  await page.screenshot({ path: out('34-looks-recurring') })
  await page.evaluate("document.documentElement.classList.add('dark')")
  await page.evaluate("location.hash = '/insights'")
  await expect(page.getByRole('article').first()).toBeVisible()
  await page.waitForTimeout(400)
  await page.screenshot({ path: out('35-insights-dark') })
  await page.keyboard.press('Control+6')
  await expect(page.getByRole('heading', { name: 'Budget' })).toBeVisible()
  await page.waitForTimeout(400)
  await page.screenshot({ path: out('22-budget-dark') })
  await page.keyboard.press('Control+9')
  await expect(page.getByRole('region', { name: 'Assumptions' })).toBeVisible()
  await page.waitForTimeout(400)
  await page.screenshot({ path: out('31-forecast-dark') })
  await page.evaluate("document.documentElement.classList.remove('dark')")
  await page.getByRole('button', { name: 'Leave demo' }).click()
  await page.evaluate("document.documentElement.classList.add('dark')")
  await page.keyboard.press('Control+1')
  await page.screenshot({ path: out('07-overview-dark') })

  await app.close()
  rmSync(dataDir, { recursive: true, force: true })
})
